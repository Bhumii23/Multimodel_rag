"""## 4. Structure-Aware Chunking

This walks the document tree **once**. Every heading pushes/pops a stack based on its nesting `level`,
so each element (text, list item, table row, image) gets tagged with the **full breadcrumb** of ancestor
headings it belongs to — not just "the last heading seen," which breaks on nested subsections and is
why tables were getting linked to the wrong section before.

Tables are expanded row-by-row *at the point they're encountered*, while the current heading stack is
still in scope, so each row inherits the correct section path directly (no separate matching pass needed).

Images are sent to Gemini for a short caption ("Image (Section: ...): <description>"), and that caption is
indexed exactly like a text chunk — so an image becomes searchable through the same hybrid search + rerank
pipeline as everything else, with no separate image index or embedding model required.
"""

# 5. Build the heading hierarchy + chunks in a single pass

class Section:
    def __init__(self, title, level, parent=None):
        self.title = title
        self.level = level
        self.parent = parent

    def path(self):
        titles, node = [], self
        while node is not None and node.parent is not None:
            titles.append(node.title)
            node = node.parent
        return list(reversed(titles))


def get_item_text(item):
    # Docling: .text in most versions, .get_text() in others. Never use str(item) directly (it returns repr).
    for attr in ("text", "caption_text"):
        v = getattr(item, attr, None)
        if isinstance(v, str) and v.strip():
            return v.strip()
    try:
        t = item.get_text()
        if isinstance(t, str) and t.strip():
            return t.strip()
    except Exception:
        pass
    s = str(item).strip()
    if s.startswith(type(item).__name__):
        return ""
    return s


def classify(item):
    # Robust across docling versions: prefer .label, fallback to class name
    try:
        label = str(getattr(item, "label", "")).lower()
    except Exception:
        label = ""
    raw = type(item).__name__
    if "SectionHeader" in raw or "Title" in raw or "section_header" in label or label.endswith("title"):
        return "heading"
    if "Table" in raw or label == "table":
        return "table"
    if "Picture" in raw or label == "picture":
        return "picture"
    if "List" in raw or "list_item" in label:
        return "list_item"
    if "Text" in raw or "paragraph" in label or "text" in label or "code" in label or "formula" in label:
        return "text"
    txt = get_item_text(item)
    return "text" if txt else "other"


def get_page(item):
    # Docling items expose page number via item.prov[0].page_no, NOT item.page_number
    try:
        return item.prov[0].page_no if item.prov else None
    except Exception:
        return None


@observe(name="caption_image")
def caption_image(item, doc, section_context):
    # Sends the extracted image to Gemini and gets back a text description.
    # No CLIP / separate embedding model needed - the caption is just indexed
    # like any other text chunk, in the SAME vector space as everything else.
    try:
        pil_image = item.get_image(doc)
        if pil_image is None:
            return None

        buffer = io.BytesIO()
        pil_image.save(buffer, format="PNG")
        image_bytes = buffer.getvalue()

        prompt = (
            f"Describe this image in 1-3 sentences. Focus on any data, labels, "
            f"numbers, or text visible in it. It appears under the section: '{section_context}'."
        )
        response = vision_model.generate_content([
            prompt,
            {"mime_type": "image/png", "data": image_bytes},
        ])
        return response.text.strip()
    except Exception as e:
        print(f"Skipping an image under '{section_context}': {e}")
        return None


@observe(name="build_document_index")
def build_document_index(doc, user_id, doc_id, doc_name):
    root = Section("Document Root", level=-1)
    heading_stack = [root]
    chunks = []
    element_counter = 0

    for item, level in doc.iterate_items():
        category = classify(item)
        page = get_page(item)

        if category == "heading":
            heading_text = get_item_text(item)
            # Pop headings that are the same depth or deeper than this one
            while len(heading_stack) > 1 and heading_stack[-1].level >= level:
                heading_stack.pop()
            node = Section(heading_text, level, parent=heading_stack[-1])
            heading_stack.append(node)

            # Index the heading itself too, so questions about a section title
            # ("what does section 3 cover?") can retrieve it directly.
            if len(heading_text) >= 3:
                chunks.append({
                    "id": str(uuid.uuid4()),
                    "element_id": element_counter,
                    "text": heading_text,
                    "metadata": {
                        "type": "heading",
                        "section": " > ".join(node.path()) or "Document Root",
                        "page": page if page is not None else 0,
                        "table_id": -1,
                    },
                })
            element_counter += 1
            continue

        current_section = " > ".join(heading_stack[-1].path()) or "Document Root"

        if category == "table":
            table_id = element_counter
            try:
                df = item.export_to_dataframe(doc=doc)
                for row_idx, row in df.iterrows():
                    row_text = f"Table (Section: {current_section}): " + " | ".join(
                        f"{col}: {val}" for col, val in row.items()
                    )
                    chunks.append({
                        "id": str(uuid.uuid4()),
                        "element_id": element_counter,
                        "text": row_text,
                        "metadata": {
                            "type": "table_row",
                            "section": current_section,
                            "page": page if page is not None else 0,
                            "table_id": table_id,
                            "row_index": int(row_idx),
                        },
                    })
            except Exception as e:
                print(f"Skipping a table under '{current_section}': {e}")
            element_counter += 1
            continue

        if category == "picture":
            caption = caption_image(item, doc, current_section)
            if caption:
                chunks.append({
                    "id": str(uuid.uuid4()),
                    "element_id": element_counter,
                    "text": f"Image (Section: {current_section}): {caption}",
                    "metadata": {
                        "type": "image_caption",
                        "section": current_section,
                        "page": page if page is not None else 0,
                        "table_id": -1,
                    },
                })
            element_counter += 1
            continue

        text = get_item_text(item)
        if len(text) < 5:
            element_counter += 1
            continue

        chunks.append({
            "id": str(uuid.uuid4()),
            "element_id": element_counter,
            "text": text,
            "metadata": {
                "type": category,
                "section": current_section,
                "page": page if page is not None else 0,
                "table_id": -1,
            },
        })
        element_counter += 1

    # Tag every chunk for multi-PDF + per-user isolation
    for c in chunks:
        c["metadata"]["user_id"] = user_id
        c["metadata"]["doc_id"] = doc_id
        c["metadata"]["doc_name"] = doc_name
    return chunks


