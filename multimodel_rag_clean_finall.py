"""## 8. Retrieval: Hybrid Search + Reranking

Vector search (semantic) and BM25 (keyword) each catch things the other misses — vector search finds
paraphrases, BM25 finds exact names/numbers. Combining them, then reranking the top candidates with a
cross-encoder, gives noticeably better precision than either alone.
"""

# 9. Hybrid Search per-user (vector + BM25, normalized and weighted)

def min_max_normalize(scores):
    scores = np.array(scores, dtype=float)
    if len(scores) == 0:
        return scores
    lo, hi = scores.min(), scores.max()
    if hi == lo:
        return np.ones_like(scores)
    return (scores - lo) / (hi - lo)


@observe(name="hybrid_search")
def hybrid_search(user_id, query, top_k=20, vector_weight=0.7, keyword_weight=0.3):
    store = get_user_store(user_id)
    chunks_u, collection, bm25 = store["chunks"], store["collection"], store["bm25"]
    query_embedding = embedding_model.encode([query], convert_to_numpy=True)[0]
    n_results = min(top_k, len(chunks_u))
    if n_results == 0:
        return []
    chroma_results = collection.query(query_embeddings=[query_embedding.tolist()], n_results=n_results)

    vector_scores = {
        cid: 1 / (1 + dist)
        for cid, dist in zip(chroma_results["ids"][0], chroma_results["distances"][0])
    }

    bm25_scores = bm25.get_scores(query.lower().split())
    normalized_bm25 = min_max_normalize(bm25_scores)

    combined = []
    for idx, chunk in enumerate(chunks_u):
        cid = f"chunk_{chunk['id']}"
        score = (vector_weight * vector_scores.get(cid, 0.0)) + (keyword_weight * normalized_bm25[idx])
        combined.append({
            "chunk_id": cid,
            "element_id": chunk["element_id"],
            "text": chunk["text"],
            "metadata": chunk["metadata"],
            "score": float(score),
        })

    combined.sort(key=lambda x: x["score"], reverse=True)
    return combined[:top_k]

# 10. Cross-Encoder Reranking

@observe(name="rerank_results")
def rerank_results(query, results, top_k=5):
    if not results:
        return []
    pairs = [[query, r["text"]] for r in results]
    scores = reranker.predict(pairs)
    for r, s in zip(results, scores):
        r["rerank_score"] = float(s)
    results.sort(key=lambda x: x["rerank_score"], reverse=True)
    return results[:top_k]

"""## 11. Structure-Aware Context Expansion

- **Prose/heading hits:** pull neighboring chunks (by `element_id`) that share the *same section breadcrumb*,
  so the surrounding sentences come along instead of one isolated line.
- **Table row hits:** pull sibling rows from the *same table* (via `table_id`), so the LLM sees the whole
  table instead of one row out of context.
"""

# 11. Structure-Aware Context Expansion (per-user)

def expand_context(user_id, reranked_results, window_size=2, max_table_siblings=8):
    store = get_user_store(user_id)
    chunks_u, chunk_by_element_id = store["chunks"], store["chunk_by_element_id"]
    expanded = []
    seen_ids = set()

    for hit in reranked_results:
        group = [hit]
        seen_ids.add(hit["chunk_id"])

        if hit["metadata"]["type"] == "table_row":
            table_id = hit["metadata"]["table_id"]
            doc_id = hit["metadata"].get("doc_id")
            siblings = [
                c for c in chunks_u
                if c["metadata"]["table_id"] == table_id and c["metadata"].get("doc_id") == doc_id and f"chunk_{c['id']}" != hit["chunk_id"]
            ][:max_table_siblings]
            for s in siblings:
                cid = f"chunk_{s['id']}"
                if cid not in seen_ids:
                    group.append({"chunk_id": cid, "element_id": s["element_id"], "text": s["text"], "metadata": s["metadata"]})
                    seen_ids.add(cid)
        else:
            for offset in range(-window_size, window_size + 1):
                neighbor = chunk_by_element_id.get(hit["element_id"] + offset)
                if neighbor is None:
                    continue
                if neighbor["metadata"]["section"] != hit["metadata"]["section"]:
                    continue
                if neighbor["metadata"].get("doc_id") != hit["metadata"].get("doc_id"):
                    continue
                cid = f"chunk_{neighbor['id']}"
                if cid not in seen_ids:
                    group.append({"chunk_id": cid, "element_id": neighbor["element_id"], "text": neighbor["text"], "metadata": neighbor["metadata"]})
                    seen_ids.add(cid)

        group.sort(key=lambda x: x["element_id"])
        expanded.append({"retrieved": hit, "context_chunks": group})

    return expanded

# 12. Assemble Context & Generate Answer

def assemble_context(expanded_results, max_chars=10000):
    seen_texts = set()
    parts = []
    for group in expanded_results:
        for c in group["context_chunks"]:
            if c["text"] in seen_texts:
                continue
            seen_texts.add(c["text"])
            meta = c["metadata"]
            parts.append(f"[Doc: {meta.get('doc_name','?')} | Section: {meta['section']} | Page: {meta['page']}]\n{c['text']}")
    context = "\n\n".join(parts)
    if len(context) > max_chars:
        context = context[:max_chars] + "\n[... context truncated ...]"
    return context


def create_rag_prompt(query, context):
    return (
        "Answer the question using ONLY the context below. "
        "If the answer is not in the context, say you don't know.\n\n"
        f"Context:\n{context}\n\nQuestion: {query}"
    )


@observe(name="generate_answer")
def generate_answer(query, context):
    prompt = create_rag_prompt(query, context)
    response = llm.invoke(prompt)
    return response.content  # NOTE: .content, not .text

# 13. Top-Level Orchestrator (per-user, Langfuse-traced)

@observe(name="ask")
def ask(user_id, query, top_k=5):
    candidates = hybrid_search(user_id, query, top_k=20)
    reranked = rerank_results(query, candidates, top_k=top_k)
    expanded = expand_context(user_id, reranked)
    context = assemble_context(expanded)
    answer = generate_answer(query, context)
    sources = [
        {"doc": r["metadata"].get("doc_name"), "section": r["metadata"]["section"], "page": r["metadata"]["page"], "type": r["metadata"]["type"]}
        for r in reranked
    ]
    try:
        # Attempting to log score. In newer versions, it requires a trace_id or is called differently.
        langfuse.score(name="retrieved_chunks", value=len(reranked))
    except Exception as e:
        print(f"[Langfuse Warning] Could not log score: {e}")
    return {"user_id": user_id, "query": query, "answer": answer, "context": context, "sources": sources}

