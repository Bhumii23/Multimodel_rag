# 7. Index chunks into per-user ChromaDB + BM25

def prepare_metadata(metadata):
    clean = {}
    for key, value in metadata.items():
        if value is None:
            continue
        elif isinstance(value, (str, int, float, bool)):
            clean[key] = value
        else:
            clean[key] = str(value)
    return clean


@observe(name="ingest_pdfs_for_user")
def ingest_pdfs_for_user(user_id, pdf_paths):
    store = get_user_store(user_id)
    added_new_pdf = False

    for pdf_path in pdf_paths:
        if pdf_path in store["docs"]:
            print(f"Skipping already ingested {pdf_path} for {user_id}")
            continue

        doc_id = f"{pdf_path}_{uuid.uuid4().hex[:8]}"

        # parse_pdf must handle PDF extraction and image captions
        doc = parse_pdf(pdf_path)

        # build_document_index must turn extracted content into chunks
        new_chunks = build_document_index(
            doc, user_id, doc_id, pdf_path
        )

        store["chunks"].extend(new_chunks)
        store["docs"][pdf_path] = doc_id
        added_new_pdf = True

        print(f"{pdf_path}: {len(new_chunks)} chunks")

    if not store["chunks"]:
        print("No chunks available to index.")
        return store

    # Rebuild indices only when new documents were added
    if not added_new_pdf and store["bm25"] is not None:
        print("No new PDFs; existing indices retained.")
        return store

    chunks_u = store["chunks"]
    texts = [c["text"] for c in chunks_u]
    ids = [f"chunk_{c['id']}" for c in chunks_u]
    metadatas = [
        prepare_metadata(c["metadata"]) for c in chunks_u
    ]

    embeddings = embedding_model.encode(
        texts,
        show_progress_bar=True,
        convert_to_numpy=True
    )

    # Actually clear the collection before rebuilding it
    try:
        existing_ids = store["collection"].get()["ids"]
        if existing_ids:
            store["collection"].delete(ids=existing_ids)
    except Exception as e:
        print("Warning while clearing ChromaDB:", e)

    store["collection"].add(
        ids=ids,
        documents=texts,
        embeddings=embeddings.tolist(),
        metadatas=metadatas
    )

    tokenized_corpus = [t.lower().split() for t in texts]
    store["bm25"] = BM25Okapi(tokenized_corpus)

    store["chunk_by_element_id"] = {
        c["element_id"]: c
        for c in chunks_u
        if c["metadata"]["type"] != "table_row"
    }

    print(
        f"User {user_id}: indexed "
        f"{store['collection'].count()} chunks "
        f"from {len(store['docs'])} PDFs."
    )

    return store


